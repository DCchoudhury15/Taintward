// Cross-check against the Python SDK detector.
//
// test/fixtures/python-expected.json is written by scripts/python-detect.py
// (run `npm run crosscheck:python` to refresh it). This test runs the
// TypeScript detector on the same fixtures and expects the same spans for
// every entity type the TypeScript SDK covers.

import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { detectText } from "../src/detect/index.js";

// Texts are base64 so the fake secrets in them do not trip secret scanners.
interface Case {
  id: string;
  text_b64: string;
  key?: string;
}
interface Span {
  type: string;
  start: number;
  end: number;
  fingerprint: string;
}

const cases: Case[] = JSON.parse(readFileSync(new URL("./fixtures/detect-cases.json", import.meta.url), "utf8"));
const expected: { python_detector_mode: string; cases: Record<string, { spans: Span[] }> } = JSON.parse(
  readFileSync(new URL("./fixtures/python-expected.json", import.meta.url), "utf8"),
);

const norm = (s: Span[]) =>
  s
    .map((x) => `${x.type}:${x.start}-${x.end}:${x.fingerprint}`)
    .sort();

describe("cross-check with the Python detector", () => {
  it("was generated by the full Python detector", () => {
    expect(expected.python_detector_mode).toBe("full");
    expect(Object.keys(expected.cases).length).toBe(cases.length);
  });

  for (const c of cases) {
    it(c.id, () => {
      const text = Buffer.from(c.text_b64, "base64").toString("utf8");
      const js = detectText(text, c.key ? { key: c.key } : {}).map((d) => ({
        type: d.entityType,
        start: d.start,
        end: d.end,
        fingerprint: d.fingerprint,
      }));
      const py = expected.cases[c.id]!.spans;
      expect(norm(js)).toEqual(norm(py));
    });
  }
});
