#!/usr/bin/env sh
# Regenerates the hashed lock files the Docker images install with
# `pip install --require-hashes`. Run from the repo root after changing
# dependencies in pyproject.toml or after updating constraints.txt:
#
#   sh deploy/requirements/update.sh
#
# Needs uv (https://docs.astral.sh/uv/). Versions come from constraints.txt,
# so the images get the same versions CI tests with. The lock files list
# hashes for every wheel of each version, so they also work on arm64.
set -eu

out=deploy/requirements
# The spaCy model is not on PyPI. Pin its wheel by URL and sha256.
model='en_core_web_sm @ https://github.com/explosion/spacy-models/releases/download/en_core_web_sm-3.8.0/en_core_web_sm-3.8.0-py3-none-any.whl#sha256=1932429db727d4bff3deed6b34cfc05df17794f4a52eeb26cf8928f7c1a0fb85'

tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
echo "$model" > "$tmp/model.in"

compile() {
    # $1 = output file, rest = extra uv arguments
    file=$1
    shift
    uv pip compile pyproject.toml "$tmp/model.in" "$@" \
        --constraints constraints.txt \
        --python-version 3.12 \
        --generate-hashes \
        --no-header \
        --no-annotate \
        --quiet \
        --output-file "$tmp/out.txt"
    {
        echo "# Generated by deploy/requirements/update.sh. Do not edit by hand."
        cat "$tmp/out.txt"
    } > "$file"
}

# demo image: runtime dependencies only.
compile "$out/runtime.txt"
# gateway image: runtime plus the mcp, redis and postgres extras.
compile "$out/gateway.txt" --extra mcp --extra redis --extra postgres

echo "wrote $out/runtime.txt and $out/gateway.txt"
